import { useMutation } from "@tanstack/react-query";
import {
  ArrowLeft,
  ArrowRight,
  CalendarDays,
  Check,
  Copy,
  GraduationCap,
  Link2,
  Plus,
  Sparkles,
  Trash2,
} from "lucide-react";
import { useMemo, useState } from "react";
import { Link, useNavigate, useParams, useSearchParams } from "react-router-dom";

import { formatDate, type QuizQuestionType } from "@studybuddy/shared";

import { QuizRunner } from "@/components/quiz-runner";
import {
  Badge,
  Button,
  Card,
  EmptyState,
  Field,
  Input,
  Modal,
  Progress,
  Select,
  Textarea,
} from "@/components/ui";
import { requestQuiz } from "@/lib/structured";
import { copyToClipboard, percent } from "@/lib/utils";
import { useStudyStore } from "@/store/study";
import { toast } from "@/store/toast";

const TYPES: Array<{ id: QuizQuestionType; label: string }> = [
  { id: "single", label: "Single choice" },
  { id: "multi", label: "Multi-select" },
  { id: "tf", label: "True / false" },
];

export default function QuizPage() {
  const { quizId } = useParams();
  const [searchParams] = useSearchParams();
  const navigate = useNavigate();

  const quizzes = useStudyStore((state) => state.quizzes);
  const attempts = useStudyStore((state) => state.attempts);
  const spaces = useStudyStore((state) => state.spaces);
  const notes = useStudyStore((state) => state.notes);
  const addQuiz = useStudyStore((state) => state.addQuiz);
  const deleteQuiz = useStudyStore((state) => state.deleteQuiz);
  const addAttempt = useStudyStore((state) => state.addAttempt);
  const addSession = useStudyStore((state) => state.addSession);
  const toggleQuizShare = useStudyStore((state) => state.toggleQuizShare);

  const [open, setOpen] = useState(false);
  const [topic, setTopic] = useState(searchParams.get("topic") ?? "");
  const [count, setCount] = useState(5);
  const [difficulty, setDifficulty] = useState<"easy" | "medium" | "hard">("medium");
  const [types, setTypes] = useState<QuizQuestionType[]>(["single", "tf"]);
  const [sourceText, setSourceText] = useState("");
  const [spaceId, setSpaceId] = useState(searchParams.get("space") ?? "");
  const [noteId, setNoteId] = useState("");

  const quiz = quizzes.find((item) => item.id === quizId);
  const quizAttempts = useMemo(
    () =>
      attempts
        .filter((attempt) => attempt.quizId === quizId)
        .sort((a, b) => a.createdAt.localeCompare(b.createdAt)),
    [attempts, quizId],
  );

  const mutation = useMutation({
    mutationFn: async () =>
      requestQuiz({
        topic: topic.trim(),
        difficulty,
        count,
        types: types.length > 0 ? types : ["single"],
        sourceText: sourceText.trim() || undefined,
      }),
    onSuccess: ({ quiz: generated, mode }) => {
      const id = addQuiz({
        spaceId: spaceId || null,
        quiz: generated,
      });
      toast(
        mode === "demo"
          ? "Quiz created with the offline generator."
          : "Quiz generated by Aeva.",
        "success",
      );
      setOpen(false);
      setTopic("");
      setSourceText("");
      navigate(`/app/quiz/${id}`);
    },
    onError: () => toast("Could not generate that quiz. Try a shorter topic.", "error"),
  });

  if (quiz) {
    const best = quizAttempts.reduce((max, attempt) => Math.max(max, attempt.scorePct), 0);
    const shareUrl = quiz.shareToken
      ? `${window.location.origin}${window.location.pathname}#/share/${quiz.shareToken}`
      : null;

    return (
      <div className="space-y-5">
        <Link
          to="/app/quiz"
          className="inline-flex items-center gap-1.5 text-[12.5px] text-muted-foreground hover:text-foreground"
        >
          <ArrowLeft className="h-3.5 w-3.5" />
          All quizzes
        </Link>

        <div className="flex flex-wrap items-start justify-between gap-4">
          <div>
            <div className="flex flex-wrap items-center gap-2">
              <h1 className="text-2xl font-semibold tracking-tight">{quiz.title}</h1>
              <Badge variant="primary">{quiz.difficulty}</Badge>
            </div>
            <p className="mt-1 text-sm text-muted-foreground">
              {quiz.questions.length} questions · {quiz.topic} · created {formatDate(quiz.createdAt)}
            </p>
          </div>
          <div className="flex flex-wrap gap-2">
            <Button
              variant="secondary"
              size="sm"
              onClick={async () => {
                const token = toggleQuizShare(quiz.id);
                if (token) {
                  const url = `${window.location.origin}${window.location.pathname}#/share/${token}`;
                  try {
                    await copyToClipboard(url);
                    toast("Share link copied.", "success");
                  } catch {
                    toast("Share link created. Copy it from the address bar.", "info");
                  }
                } else {
                  toast("Share link disabled.", "info");
                }
              }}
            >
              <Link2 className="h-3.5 w-3.5" />
              {quiz.shareToken ? "Disable share" : "Share"}
            </Button>
            <Button
              variant="outline"
              size="sm"
              className="text-danger"
              onClick={() => {
                deleteQuiz(quiz.id);
                navigate("/app/quiz");
                toast("Quiz deleted.", "info");
              }}
            >
              <Trash2 className="h-3.5 w-3.5" />
              Delete
            </Button>
          </div>
        </div>

        {shareUrl ? (
          <Card className="flex flex-wrap items-center gap-2 p-3">
            <Link2 className="h-4 w-4 text-primary" />
            <p className="min-w-0 flex-1 truncate text-[12px] text-muted-foreground">{shareUrl}</p>
            <Button
              size="sm"
              variant="ghost"
              onClick={async () => {
                try {
                  await copyToClipboard(shareUrl);
                  toast("Copied.", "success");
                } catch {
                  toast("Copy failed.", "error");
                }
              }}
            >
              <Copy className="h-3.5 w-3.5" />
              Copy
            </Button>
          </Card>
        ) : null}

        <div className="grid gap-4 lg:grid-cols-[1fr_280px]">
          <div className="min-w-0">
            <QuizRunner
              questions={quiz.questions}
              onGraded={(result) => {
                addAttempt({
                  quizId: quiz.id,
                  answers: Object.fromEntries(
                    result.results.map((item) => [item.questionId, item.given]),
                  ),
                  scorePct: result.scorePct,
                  feedback: `${result.correctCount}/${result.total} correct`,
                });
                addSession({ kind: "quiz", durationMin: 4 });
                toast(`Attempt saved — ${result.scorePct}%.`, "success");
              }}
            />
          </div>

          <aside className="space-y-3">
            <Card className="p-4">
              <p className="text-[11px] uppercase tracking-wide text-muted-foreground">Best score</p>
              <p className="mt-1 text-2xl font-semibold">{best}%</p>
              <Progress
                value={best}
                className="mt-2 h-1.5"
                tone={best >= 75 ? "success" : best >= 50 ? "warning" : "danger"}
              />
              <p className="mt-2 text-[11px] text-muted-foreground">
                {quizAttempts.length} attempt{quizAttempts.length === 1 ? "" : "s"}
              </p>
            </Card>

            <Card className="p-4">
              <p className="text-sm font-semibold">Attempt history</p>
              {quizAttempts.length === 0 ? (
                <p className="mt-2 text-xs text-muted-foreground">
                  Submit the quiz to start tracking your scores.
                </p>
              ) : (
                <ul className="mt-2 space-y-2">
                  {[...quizAttempts].reverse().slice(0, 6).map((attempt) => (
                    <li key={attempt.id} className="flex items-center justify-between gap-2 text-xs">
                      <span className="text-muted-foreground">
                        {new Date(attempt.createdAt).toLocaleDateString(undefined, {
                          day: "numeric",
                          month: "short",
                        })}
                      </span>
                      <span
                        className={
                          attempt.scorePct >= 75
                            ? "font-semibold text-success"
                            : attempt.scorePct >= 50
                              ? "font-semibold text-warning"
                              : "font-semibold text-danger"
                        }
                      >
                        {attempt.scorePct}%
                      </span>
                    </li>
                  ))}
                </ul>
              )}
            </Card>

            <Card className="p-4">
              <p className="text-sm font-semibold">Weakest questions</p>
              {quizAttempts.length === 0 ? (
                <p className="mt-2 text-xs text-muted-foreground">No data yet.</p>
              ) : (
                <ul className="mt-2 space-y-2 text-[11.5px] text-muted-foreground">
                  {quiz.questions.slice(0, 3).map((question) => (
                    <li key={question.id} className="line-clamp-2">
                      • {question.prompt}
                    </li>
                  ))}
                </ul>
              )}
            </Card>
          </aside>
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Quizzes</h1>
          <p className="mt-1 text-sm text-muted-foreground">
            Generate a quiz from a topic, a note or an answer — graded instantly with explanations.
          </p>
        </div>
        <Button onClick={() => setOpen(true)}>
          <Sparkles className="h-4 w-4" />
          Generate quiz
        </Button>
      </div>

      {quizzes.length === 0 ? (
        <EmptyState
          icon={<GraduationCap className="h-5 w-5" />}
          title="No quizzes yet"
          description="Pick a topic and Aeva will build a quiz with explanations for every question."
          action={
            <Button onClick={() => setOpen(true)}>
              <Plus className="h-4 w-4" />
              Create your first quiz
            </Button>
          }
        />
      ) : (
        <div className="grid gap-3 sm:grid-cols-2">
          {quizzes.map((item) => {
            const itemAttempts = attempts.filter((attempt) => attempt.quizId === item.id);
            const best = itemAttempts.reduce((max, attempt) => Math.max(max, attempt.scorePct), 0);
            const last = itemAttempts[itemAttempts.length - 1];
            const space = spaces.find((candidate) => candidate.id === item.spaceId);
            return (
              <Card key={item.id} className="flex h-full flex-col p-4">
                <div className="flex items-start justify-between gap-2">
                  <Link to={`/app/quiz/${item.id}`} className="min-w-0">
                    <p className="line-clamp-1 text-[14px] font-semibold hover:text-primary">
                      {item.title}
                    </p>
                    <p className="mt-0.5 text-[11.5px] text-muted-foreground">
                      {item.questions.length} questions · {item.difficulty}
                      {space ? ` · ${space.name}` : ""}
                    </p>
                  </Link>
                  <Badge variant={itemAttempts.length > 0 ? "primary" : "neutral"}>
                    {itemAttempts.length > 0 ? `Best ${best}%` : "New"}
                  </Badge>
                </div>

                {itemAttempts.length > 0 ? (
                  <div className="mt-3">
                    <Progress
                      value={best}
                      className="h-1.5"
                      tone={best >= 75 ? "success" : best >= 50 ? "warning" : "danger"}
                    />
                    <p className="mt-1.5 flex items-center gap-1 text-[10.5px] text-muted-foreground">
                      <CalendarDays className="h-3 w-3" />
                      Last attempt {last ? formatDate(last.createdAt) : "—"} ·{" "}
                      {percent(itemAttempts.filter((attempt) => attempt.scorePct >= 60).length, itemAttempts.length)}
                      % passed
                    </p>
                  </div>
                ) : (
                  <p className="mt-3 text-[11.5px] text-muted-foreground">
                    Not attempted yet — start when you are ready.
                  </p>
                )}

                <div className="mt-auto flex items-center gap-2 pt-4">
                  <Link to={`/app/quiz/${item.id}`} className="flex-1">
                    <Button variant="secondary" size="sm" className="w-full">
                      {itemAttempts.length > 0 ? "Retake quiz" : "Start quiz"}
                      <ArrowRight className="h-3.5 w-3.5" />
                    </Button>
                  </Link>
                  <Button
                    variant="ghost"
                    size="icon-sm"
                    aria-label={`Delete ${item.title}`}
                    onClick={() => {
                      deleteQuiz(item.id);
                      toast("Quiz deleted.", "info");
                    }}
                  >
                    <Trash2 className="h-3.5 w-3.5" />
                  </Button>
                </div>
              </Card>
            );
          })}
        </div>
      )}

      <Modal
        open={open}
        onClose={() => setOpen(false)}
        title="Generate a quiz"
        description="Aeva writes questions, options and an explanation for each answer."
        size="lg"
        footer={
          <>
            <Button variant="ghost" onClick={() => setOpen(false)}>
              Cancel
            </Button>
            <Button
              onClick={() => mutation.mutate()}
              loading={mutation.isPending}
              disabled={topic.trim().length < 2}
            >
              <Sparkles className="h-4 w-4" />
              Generate quiz
            </Button>
          </>
        }
      >
        <div className="grid gap-4 sm:grid-cols-2">
          <Field label="Topic" hint="Required" className="sm:col-span-2">
            <Input
              value={topic}
              onChange={(event) => setTopic(event.target.value)}
              placeholder="e.g. Photosynthesis, quadratic equations, the Cold War"
              autoFocus
            />
          </Field>

          <Field label="Questions">
            <Select value={count} onChange={(event) => setCount(Number(event.target.value))}>
              {[3, 5, 8, 10].map((value) => (
                <option key={value} value={value}>
                  {value} questions
                </option>
              ))}
            </Select>
          </Field>

          <Field label="Difficulty">
            <Select
              value={difficulty}
              onChange={(event) => setDifficulty(event.target.value as typeof difficulty)}
            >
              <option value="easy">Easy — recall</option>
              <option value="medium">Medium — understanding</option>
              <option value="hard">Hard — application</option>
            </Select>
          </Field>

          <div className="space-y-1.5 sm:col-span-2">
            <p className="text-sm font-medium">Question types</p>
            <div className="flex flex-wrap gap-2">
              {TYPES.map((type) => {
                const active = types.includes(type.id);
                return (
                  <button
                    key={type.id}
                    type="button"
                    aria-pressed={active}
                    onClick={() =>
                      setTypes((current) =>
                        active ? current.filter((id) => id !== type.id) : [...current, type.id],
                      )
                    }
                    className={`inline-flex items-center gap-1.5 rounded-full border px-3 py-1.5 text-[12px] font-medium transition ${
                      active
                        ? "border-primary bg-primary/10 text-primary"
                        : "border-border text-muted-foreground hover:text-foreground"
                    }`}
                  >
                    {active ? <Check className="h-3 w-3" /> : null}
                    {type.label}
                  </button>
                );
              })}
            </div>
          </div>

          <Field label="Study space">
            <Select value={spaceId} onChange={(event) => setSpaceId(event.target.value)}>
              <option value="">No space</option>
              {spaces.map((space) => (
                <option key={space.id} value={space.id}>
                  {space.name}
                </option>
              ))}
            </Select>
          </Field>

          <Field label="Use an existing note">
            <Select
              value={noteId}
              onChange={(event) => {
                setNoteId(event.target.value);
                const note = notes.find((item) => item.id === event.target.value);
                if (note) {
                  setSourceText(note.markdown);
                  if (!topic.trim()) setTopic(note.title);
                }
              }}
            >
              <option value="">None</option>
              {notes.map((note) => (
                <option key={note.id} value={note.id}>
                  {note.title}
                </option>
              ))}
            </Select>
          </Field>

          <Field
            label="Source material (optional)"
            hint="Paste notes or a reading for questions grounded in your material."
            className="sm:col-span-2"
          >
            <Textarea
              value={sourceText}
              onChange={(event) => setSourceText(event.target.value)}
              rows={5}
              placeholder="Paste a passage, your class notes, or a summary…"
            />
          </Field>
        </div>
      </Modal>
    </div>
  );
}
