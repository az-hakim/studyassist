import { useMutation } from "@tanstack/react-query";
import { ArrowLeft, ArrowRight, Layers, Plus, Sparkles, Trash2 } from "lucide-react";
import { useState } from "react";
import { Link, useNavigate, useParams, useSearchParams } from "react-router-dom";

import { formatDate, type Rating } from "@studybuddy/shared";

import { FlashcardRunner } from "@/components/flashcard-runner";
import {
  Badge,
  Button,
  Card,
  EmptyState,
  Field,
  Input,
  Modal,
  Progress,
  Select,
  Textarea,
} from "@/components/ui";
import { requestDeck } from "@/lib/structured";
import { useStudyStore } from "@/store/study";
import { toast } from "@/store/toast";

const RATING_LABELS: Array<{ id: Rating; label: string; tone: string }> = [
  { id: "easy", label: "Easy", tone: "text-success" },
  { id: "medium", label: "Medium", tone: "text-primary" },
  { id: "hard", label: "Hard", tone: "text-warning" },
  { id: "needs_revision", label: "Needs revision", tone: "text-danger" },
];

export default function FlashcardsPage() {
  const { deckId } = useParams();
  const [searchParams] = useSearchParams();
  const navigate = useNavigate();

  const decks = useStudyStore((state) => state.decks);
  const spaces = useStudyStore((state) => state.spaces);
  const notes = useStudyStore((state) => state.notes);
  const addDeck = useStudyStore((state) => state.addDeck);
  const deleteDeck = useStudyStore((state) => state.deleteDeck);
  const rateCard = useStudyStore((state) => state.rateCard);
  const addSession = useStudyStore((state) => state.addSession);

  const [open, setOpen] = useState(false);
  const [topic, setTopic] = useState("");
  const [count, setCount] = useState(8);
  const [spaceId, setSpaceId] = useState(searchParams.get("space") ?? "");
  const [sourceText, setSourceText] = useState("");
  const [noteId, setNoteId] = useState("");

  const deck = decks.find((item) => item.id === deckId);

  const mutation = useMutation({
    mutationFn: async () =>
      requestDeck({
        topic: topic.trim(),
        count,
        sourceText: sourceText.trim() || undefined,
      }),
    onSuccess: ({ deck: generated, mode }) => {
      const id = addDeck({
        spaceId: spaceId || null,
        name: `${generated.topic} deck`,
        topic: generated.topic,
        cards: generated.cards,
      });
      toast(
        mode === "demo" ? "Deck built with the offline generator." : "Deck generated by Aeva.",
        "success",
      );
      setOpen(false);
      setTopic("");
      setSourceText("");
      navigate(`/app/flashcards/${id}`);
    },
    onError: () => toast("Could not build that deck. Try another topic.", "error"),
  });

  if (deck) {
    const rated = deck.cards.filter((card) => card.rating).length;
    const counts = RATING_LABELS.map((rating) => ({
      ...rating,
      count: deck.cards.filter((card) => card.rating === rating.id).length,
    }));

    return (
      <div className="space-y-5">
        <Link
          to="/app/flashcards"
          className="inline-flex items-center gap-1.5 text-[12.5px] text-muted-foreground hover:text-foreground"
        >
          <ArrowLeft className="h-3.5 w-3.5" />
          All decks
        </Link>

        <div className="flex flex-wrap items-start justify-between gap-4">
          <div>
            <h1 className="text-2xl font-semibold tracking-tight">{deck.name}</h1>
            <p className="mt-1 text-sm text-muted-foreground">
              {deck.cards.length} cards · {deck.topic} · created {formatDate(deck.createdAt)}
            </p>
          </div>
          <div className="flex gap-2">
            <Badge variant="primary">{rated} rated</Badge>
            <Button
              variant="outline"
              size="sm"
              className="text-danger"
              onClick={() => {
                deleteDeck(deck.id);
                navigate("/app/flashcards");
                toast("Deck deleted.", "info");
              }}
            >
              <Trash2 className="h-3.5 w-3.5" />
              Delete
            </Button>
          </div>
        </div>

        <div className="grid gap-4 lg:grid-cols-[1fr_260px]">
          <div className="min-w-0">
            <FlashcardRunner
              cards={deck.cards}
              deckName={deck.name}
              onRate={(cardId, rating) => rateCard(deck.id, cardId, rating)}
            />
          </div>
          <aside className="space-y-3">
            <Card className="p-4">
              <p className="text-sm font-semibold">Ratings so far</p>
              <div className="mt-3 space-y-2">
                {counts.map((rating) => (
                  <div key={rating.id}>
                    <div className="flex items-center justify-between text-[11.5px]">
                      <span className={rating.tone}>{rating.label}</span>
                      <span className="text-muted-foreground">{rating.count}</span>
                    </div>
                    <Progress
                      value={(rating.count / Math.max(1, deck.cards.length)) * 100}
                      className="mt-1 h-1"
                      tone={
                        rating.id === "easy"
                          ? "success"
                          : rating.id === "hard"
                            ? "warning"
                            : rating.id === "needs_revision"
                              ? "danger"
                              : "primary"
                      }
                    />
                  </div>
                ))}
              </div>
              <Button
                variant="secondary"
                size="sm"
                className="mt-4 w-full"
                onClick={() => {
                  addSession({ kind: "flashcards", durationMin: 5 });
                  toast("Session logged.", "success");
                }}
              >
                Log a 5 min session
              </Button>
            </Card>

            <Card className="p-4">
              <p className="text-sm font-semibold">How ratings work</p>
              <p className="mt-1.5 text-[11.5px] leading-relaxed text-muted-foreground">
                Easy adds 8 strength points, Medium 3, Hard removes 6 and Needs revision removes 12.
                Aeva uses these to schedule the next review.
              </p>
            </Card>
          </aside>
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Flashcards</h1>
          <p className="mt-1 text-sm text-muted-foreground">
            Active recall beats re-reading. Generate a deck, flip, and rate honestly.
          </p>
        </div>
        <Button onClick={() => setOpen(true)}>
          <Sparkles className="h-4 w-4" />
          Generate deck
        </Button>
      </div>

      {decks.length === 0 ? (
        <EmptyState
          icon={<Layers className="h-5 w-5" />}
          title="No decks yet"
          description="A topic is enough. Paste notes too if you want cards grounded in your material."
          action={
            <Button onClick={() => setOpen(true)}>
              <Plus className="h-4 w-4" />
              Build your first deck
            </Button>
          }
        />
      ) : (
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
          {decks.map((item) => {
            const rated = item.cards.filter((card) => card.rating).length;
            const easy = item.cards.filter((card) => card.rating === "easy").length;
            const space = spaces.find((candidate) => candidate.id === item.spaceId);
            return (
              <Card key={item.id} className="flex h-full flex-col p-4">
                <div className="flex items-start justify-between gap-2">
                  <Link to={`/app/flashcards/${item.id}`} className="min-w-0">
                    <p className="line-clamp-1 text-[14px] font-semibold hover:text-primary">
                      {item.name}
                    </p>
                    <p className="mt-0.5 text-[11.5px] text-muted-foreground">
                      {item.cards.length} cards
                      {space ? ` · ${space.name}` : ""}
                    </p>
                  </Link>
                  {easy > 0 ? <Badge variant="success">{easy} easy</Badge> : null}
                </div>

                <p className="mt-3 line-clamp-2 text-[12px] text-muted-foreground">
                  {item.cards[0]?.front ?? "No cards yet"}
                </p>

                <div className="mt-3">
                  <div className="flex items-center justify-between text-[10.5px] text-muted-foreground">
                    <span>Reviewed</span>
                    <span>
                      {rated}/{item.cards.length}
                    </span>
                  </div>
                  <Progress value={(rated / Math.max(1, item.cards.length)) * 100} className="mt-1 h-1" />
                </div>

                <div className="mt-auto flex items-center gap-2 pt-4">
                  <Link to={`/app/flashcards/${item.id}`} className="flex-1">
                    <Button variant="secondary" size="sm" className="w-full">
                      {rated > 0 ? "Keep reviewing" : "Start review"}
                      <ArrowRight className="h-3.5 w-3.5" />
                    </Button>
                  </Link>
                  <Button
                    variant="ghost"
                    size="icon-sm"
                    aria-label={`Delete ${item.name}`}
                    onClick={() => {
                      deleteDeck(item.id);
                      toast("Deck deleted.", "info");
                    }}
                  >
                    <Trash2 className="h-3.5 w-3.5" />
                  </Button>
                </div>
              </Card>
            );
          })}
        </div>
      )}

      <Modal
        open={open}
        onClose={() => setOpen(false)}
        title="Generate flashcards"
        description="Front is a prompt, back is a compact answer you can check yourself against."
        size="lg"
        footer={
          <>
            <Button variant="ghost" onClick={() => setOpen(false)}>
              Cancel
            </Button>
            <Button
              onClick={() => mutation.mutate()}
              loading={mutation.isPending}
              disabled={topic.trim().length < 2}
            >
              <Sparkles className="h-4 w-4" />
              Generate deck
            </Button>
          </>
        }
      >
        <div className="grid gap-4 sm:grid-cols-2">
          <Field label="Topic" hint="Required" className="sm:col-span-2">
            <Input
              value={topic}
              onChange={(event) => setTopic(event.target.value)}
              placeholder="e.g. Cell respiration, integration by parts"
              autoFocus
            />
          </Field>

          <Field label="Cards">
            <Select value={count} onChange={(event) => setCount(Number(event.target.value))}>
              {[5, 8, 12, 16, 20].map((value) => (
                <option key={value} value={value}>
                  {value} cards
                </option>
              ))}
            </Select>
          </Field>

          <Field label="Study space">
            <Select value={spaceId} onChange={(event) => setSpaceId(event.target.value)}>
              <option value="">No space</option>
              {spaces.map((space) => (
                <option key={space.id} value={space.id}>
                  {space.name}
                </option>
              ))}
            </Select>
          </Field>

          <Field label="Use an existing note">
            <Select
              value={noteId}
              onChange={(event) => {
                setNoteId(event.target.value);
                const note = notes.find((item) => item.id === event.target.value);
                if (note) {
                  setSourceText(note.markdown);
                  if (!topic.trim()) setTopic(note.title);
                }
              }}
            >
              <option value="">None</option>
              {notes.map((note) => (
                <option key={note.id} value={note.id}>
                  {note.title}
                </option>
              ))}
            </Select>
          </Field>

          <Field label="Source material (optional)" className="sm:col-span-2">
            <Textarea
              value={sourceText}
              onChange={(event) => setSourceText(event.target.value)}
              rows={5}
              placeholder="Paste notes or a passage to make extractive cards…"
            />
          </Field>
        </div>
      </Modal>
    </div>
  );
}
