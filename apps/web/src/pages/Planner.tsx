import { useMutation } from "@tanstack/react-query";
import {
  ArrowLeft,
  ArrowRight,
  CalendarClock,
  CalendarDays,
  Check,
  Circle,
  Clock,
  PlayCircle,
  Plus,
  Sparkles,
  Trash2,
} from "lucide-react";
import { useMemo, useState } from "react";
import { Link, useNavigate, useParams } from "react-router-dom";

import { formatDateShort, formatDuration } from "@studybuddy/shared";

import {
  Badge,
  Button,
  Card,
  EmptyState,
  Field,
  Input,
  Modal,
  Progress,
  Select,
  Textarea,
} from "@/components/ui";
import { requestPlan } from "@/lib/structured";
import { cn } from "@/lib/utils";
import { useStudyStore } from "@/store/study";
import { toast } from "@/store/toast";
import type { TopicStatus } from "@/store/types";

const STATUS_META: Record<TopicStatus, { label: string; variant: "neutral" | "warning" | "success" }> = {
  not_started: { label: "Not started", variant: "neutral" },
  in_progress: { label: "In progress", variant: "warning" },
  done: { label: "Done", variant: "success" },
};

function daysUntil(date: string): number {
  const target = new Date(`${date}T00:00:00`).getTime();
  if (Number.isNaN(target)) return 0;
  return Math.max(0, Math.ceil((target - Date.now()) / 86_400_000));
}

export default function PlannerPage() {
  const { planId } = useParams();
  const navigate = useNavigate();
  const plans = useStudyStore((state) => state.plans);
  const addPlan = useStudyStore((state) => state.addPlan);
  const deletePlan = useStudyStore((state) => state.deletePlan);
  const setTopicStatus = useStudyStore((state) => state.setTopicStatus);

  const [open, setOpen] = useState(false);
  const [examName, setExamName] = useState("");
  const [examDate, setExamDate] = useState("");
  const [classStream, setClassStream] = useState("");
  const [subjects, setSubjects] = useState("");
  const [dailyMinutes, setDailyMinutes] = useState(90);
  const [syllabus, setSyllabus] = useState("");
  const [confirmDelete, setConfirmDelete] = useState(false);

  const plan = plans.find((item) => item.id === planId);

  const mutation = useMutation({
    mutationFn: async () =>
      requestPlan({
        examName: examName.trim(),
        examDate,
        classStream: classStream.trim() || undefined,
        subjects: subjects
          .split(",")
          .map((item) => item.trim())
          .filter(Boolean),
        dailyMinutes,
        syllabusText: syllabus.trim() || undefined,
      }),
    onSuccess: ({ plan: generated, mode }) => {
      const id = addPlan({
        examName: generated.examName,
        examDate: generated.examDate,
        classStream: generated.classStream,
        subjects: generated.subjects,
        dailyMinutes: generated.dailyMinutes,
        days: generated.days.map((day) => ({
          id: day.id,
          date: day.date,
          topics: day.topics.map((topic) => ({
            id: topic.id,
            name: topic.name,
            subject: topic.subject,
            minutes: topic.minutes,
          })),
        })),
      });
      toast(
        mode === "demo"
          ? "Plan built with the offline planner. Connect Supabase for syllabus-aware AI plans."
          : "Plan generated by Nova.",
        "success",
      );
      setOpen(false);
      setExamName("");
      setExamDate("");
      setSubjects("");
      setSyllabus("");
      navigate(`/app/planner/${id}`);
    },
    onError: () => toast("Could not build that plan. Check the date and subjects.", "error"),
  });

  const planStats = useMemo(() => {
    if (!plan) return null;
    const topics = plan.days.flatMap((day) => day.topics);
    const done = topics.filter((topic) => topic.status === "done").length;
    const minutes = topics.reduce((sum, topic) => sum + topic.minutes, 0);
    return {
      total: topics.length,
      done,
      minutes,
      pct: topics.length > 0 ? Math.round((done / topics.length) * 100) : 0,
    };
  }, [plan]);

  if (plan && planStats) {
    const remaining = daysUntil(plan.examDate);
    return (
      <div className="space-y-5">
        <Link
          to="/app/planner"
          className="inline-flex items-center gap-1.5 text-[12.5px] text-muted-foreground hover:text-foreground"
        >
          <ArrowLeft className="h-3.5 w-3.5" />
          All plans
        </Link>

        <div className="flex flex-wrap items-start justify-between gap-4">
          <div>
            <h1 className="text-2xl font-semibold tracking-tight">{plan.examName}</h1>
            <p className="mt-1 flex flex-wrap items-center gap-x-3 gap-y-1 text-sm text-muted-foreground">
              <span className="inline-flex items-center gap-1">
                <CalendarDays className="h-4 w-4" />
                {formatDateShort(plan.examDate)}
              </span>
              <span className="inline-flex items-center gap-1">
                <Clock className="h-4 w-4" />
                {formatDuration(plan.dailyMinutes)} / day
              </span>
              <span>
                {remaining === 0 ? "Exam day" : `${remaining} day${remaining === 1 ? "" : "s"} left`}
              </span>
            </p>
            {plan.classStream ? (
              <p className="mt-1 text-xs text-muted-foreground">{plan.classStream}</p>
            ) : null}
            <div className="mt-2 flex flex-wrap gap-1.5">
              {plan.subjects.map((subject) => (
                <span key={subject} className="chip">
                  {subject}
                </span>
              ))}
            </div>
          </div>
          <div className="flex items-center gap-2">
            <Button variant="outline" size="sm" className="text-danger" onClick={() => setConfirmDelete(true)}>
              <Trash2 className="h-3.5 w-3.5" />
              Delete plan
            </Button>
          </div>
        </div>

        <Card className="p-4">
          <div className="flex items-center justify-between text-[11.5px] text-muted-foreground">
            <span>
              {planStats.done} of {planStats.total} topics complete
            </span>
            <span>{formatDuration(planStats.minutes)} total</span>
          </div>
          <Progress value={planStats.pct} className="mt-2" />
        </Card>

        <div className="space-y-3">
          {plan.days.map((day, dayIndex) => {
            const dayTopics = day.topics;
            const done = dayTopics.filter((topic) => topic.status === "done").length;
            const isToday = day.date === new Date().toISOString().slice(0, 10);
            return (
              <Card
                key={day.id}
                className={cn("overflow-hidden", isToday && "border-primary/40")}
              >
                <div className="flex flex-wrap items-center gap-2 border-b border-border/60 bg-muted/30 px-4 py-2.5">
                  <span className="flex h-7 w-7 items-center justify-center rounded-lg bg-card text-[11px] font-semibold text-muted-foreground">
                    {dayIndex + 1}
                  </span>
                  <p className="text-[13px] font-semibold">{formatDateShort(day.date)}</p>
                  {isToday ? <Badge variant="primary">Today</Badge> : null}
                  <span className="ml-auto text-[11px] text-muted-foreground">
                    {done}/{dayTopics.length} done
                  </span>
                </div>
                <div className="divide-y divide-border/50">
                  {dayTopics.map((topic) => {
                    const meta = STATUS_META[topic.status];
                    const practice = `/app/planner/${plan.id}/${topic.id}`;
                    return (
                      <div key={topic.id} className="flex flex-wrap items-center gap-2 px-4 py-3">
                        <button
                          type="button"
                          onClick={() =>
                            setTopicStatus(
                              plan.id,
                              day.id,
                              topic.id,
                              topic.status === "done" ? "not_started" : "done",
                            )
                          }
                          aria-label={
                            topic.status === "done"
                              ? `Mark ${topic.name} not started`
                              : `Mark ${topic.name} done`
                          }
                          className={cn(
                            "flex h-6 w-6 shrink-0 items-center justify-center rounded-full border transition",
                            topic.status === "done"
                              ? "border-success bg-success text-white"
                              : "border-border text-transparent hover:border-success",
                          )}
                        >
                          <Check className="h-3.5 w-3.5" />
                        </button>

                        <Link to={practice} className="min-w-0 flex-1">
                          <p
                            className={cn(
                              "truncate text-[13.5px] font-medium",
                              topic.status === "done" && "text-muted-foreground line-through",
                            )}
                          >
                            {topic.name}
                          </p>
                          <p className="text-[10.5px] text-muted-foreground">
                            {topic.subject} · {formatDuration(topic.minutes)} ·{" "}
                            {topic.lessonMarkdown ? "lesson ready" : "lesson not generated"}
                          </p>
                        </Link>

                        <Badge variant={meta.variant}>{meta.label}</Badge>

                        <Link to={practice}>
                          <Button size="sm" variant="secondary">
                            <PlayCircle className="h-3.5 w-3.5" />
                            Study
                          </Button>
                        </Link>
                      </div>
                    );
                  })}
                </div>
              </Card>
            );
          })}
        </div>

        <Modal
          open={confirmDelete}
          onClose={() => setConfirmDelete(false)}
          title="Delete this plan?"
          description="The plan and its generated lessons will be removed. Topic memories stay."
          size="sm"
          footer={
            <>
              <Button variant="ghost" onClick={() => setConfirmDelete(false)}>
                Keep it
              </Button>
              <Button
                variant="danger"
                onClick={() => {
                  deletePlan(plan.id);
                  navigate("/app/planner");
                  toast("Plan deleted.", "info");
                }}
              >
                Delete plan
              </Button>
            </>
          }
        />
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Exam planner</h1>
          <p className="mt-1 text-sm text-muted-foreground">
            Tell Nova the exam, the subjects and how long you can study. Get a day-by-day plan.
          </p>
        </div>
        <Button onClick={() => setOpen(true)}>
          <Sparkles className="h-4 w-4" />
          New exam plan
        </Button>
      </div>

      {plans.length === 0 ? (
        <EmptyState
          icon={<CalendarClock className="h-5 w-5" />}
          title="No exam plans yet"
          description="A plan turns a syllabus into lessons, practice and a countdown you can act on."
          action={
            <Button onClick={() => setOpen(true)}>
              <Plus className="h-4 w-4" />
              Build a plan
            </Button>
          }
        />
      ) : (
        <div className="grid gap-3 sm:grid-cols-2">
          {plans.map((item) => {
            const topics = item.days.flatMap((day) => day.topics);
            const done = topics.filter((topic) => topic.status === "done").length;
            const pct = topics.length ? Math.round((done / topics.length) * 100) : 0;
            const left = daysUntil(item.examDate);
            return (
              <Card key={item.id} className="flex h-full flex-col p-5">
                <div className="flex items-start justify-between gap-2">
                  <div>
                    <Link to={`/app/planner/${item.id}`}>
                      <p className="text-[15px] font-semibold hover:text-primary">{item.examName}</p>
                    </Link>
                    <p className="mt-0.5 text-[11.5px] text-muted-foreground">
                      {formatDateShort(item.examDate)} · {left} days left
                    </p>
                  </div>
                  <Badge variant={pct >= 75 ? "success" : "primary"}>{pct}%</Badge>
                </div>
                <div className="mt-3 flex flex-wrap gap-1.5">
                  {item.subjects.map((subject) => (
                    <span key={subject} className="chip">
                      {subject}
                    </span>
                  ))}
                </div>
                <Progress value={pct} className="mt-3" />
                <p className="mt-2 text-[11px] text-muted-foreground">
                  {done}/{topics.length} topics · {formatDuration(item.dailyMinutes)}/day
                </p>
                <div className="mt-auto flex items-center gap-2 pt-4">
                  <Link to={`/app/planner/${item.id}`} className="flex-1">
                    <Button variant="secondary" size="sm" className="w-full">
                      Open plan
                      <ArrowRight className="h-3.5 w-3.5" />
                    </Button>
                  </Link>
                  <Button
                    variant="ghost"
                    size="icon-sm"
                    aria-label={`Delete ${item.examName}`}
                    onClick={() => {
                      deletePlan(item.id);
                      toast("Plan deleted.", "info");
                    }}
                  >
                    <Trash2 className="h-3.5 w-3.5" />
                  </Button>
                </div>
              </Card>
            );
          })}
        </div>
      )}

      <Modal
        open={open}
        onClose={() => setOpen(false)}
        title="Build an exam plan"
        description="Nova distributes topics across the days you have left, within your daily budget."
        size="lg"
        footer={
          <>
            <Button variant="ghost" onClick={() => setOpen(false)}>
              Cancel
            </Button>
            <Button
              onClick={() => mutation.mutate()}
              loading={mutation.isPending}
              disabled={!examName.trim() || !examDate || subjects.trim().length === 0}
            >
              <Sparkles className="h-4 w-4" />
              Generate plan
            </Button>
          </>
        }
      >
        <div className="grid gap-4 sm:grid-cols-2">
          <Field label="Exam name" hint="Required">
            <Input
              value={examName}
              onChange={(event) => setExamName(event.target.value)}
              placeholder="Biology midterm"
              autoFocus
            />
          </Field>
          <Field label="Exam date" hint="Required">
            <Input
              type="date"
              value={examDate}
              min={new Date().toISOString().slice(0, 10)}
              onChange={(event) => setExamDate(event.target.value)}
            />
          </Field>
          <Field label="Class or stream">
            <Input
              value={classStream}
              onChange={(event) => setClassStream(event.target.value)}
              placeholder="Grade 11 · Science"
            />
          </Field>
          <Field label="Daily study time">
            <Select value={dailyMinutes} onChange={(event) => setDailyMinutes(Number(event.target.value))}>
              {[30, 45, 60, 90, 120, 180].map((value) => (
                <option key={value} value={value}>
                  {formatDuration(value)} per day
                </option>
              ))}
            </Select>
          </Field>
          <Field
            label="Subjects"
            hint="Comma separated, required"
            className="sm:col-span-2"
          >
            <Input
              value={subjects}
              onChange={(event) => setSubjects(event.target.value)}
              placeholder="Biology, Chemistry, Mathematics"
            />
          </Field>
          <Field
            label="Syllabus (optional)"
            hint="Paste unit or topic names, one per line, for a closer plan."
            className="sm:col-span-2"
          >
            <Textarea
              value={syllabus}
              onChange={(event) => setSyllabus(event.target.value)}
              rows={5}
              placeholder={"Cell respiration\nPhotosynthesis\nGenetics and inheritance"}
            />
          </Field>
        </div>
        <div className="mt-3 flex items-start gap-2 rounded-xl border border-border/60 bg-muted/30 p-3 text-[11.5px] leading-relaxed text-muted-foreground">
          <Circle className="mt-0.5 h-3 w-3 shrink-0 text-primary" />
          Lessons are generated on first open, so the plan itself stays fast to create.
        </div>
      </Modal>
    </div>
  );
}
